		protected override void Load()
		{
			PropertyShops.Create("WorldBossExchangeShop", "world_boss_golden_coin", GoldenCoinItemId, shop =>
			{
				foreach (var entry in ExchangeItems)
				{
					shop.AddItem(entry.ClassName, entry.ItemId, entry.Amount, entry.CoinCost);
				}
			});

			Dialog.RegisterPropertyShopForMap("c_Klaipe", "WorldBossExchangeShop", "GET_PVP_POINT");

			AddNpc(151072, L("[World Boss Exchange Shop] Igor"), "Igor", "c_Klaipe", -650, 750, 0, async dialog =>
			{
				dialog.SetTitle(L("World Boss Exchange Shop"));

				await dialog.Msg(L("Exchange the Golden Coins earned from World Boss battles for exclusive rewards."));

				dialog.OpenPropertyShop("WorldBossExchangeShop", string.Empty, "uphill_defense_shoppoint", "MercenaryWingShop");
			});
		}

